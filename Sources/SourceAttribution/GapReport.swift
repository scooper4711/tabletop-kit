import Foundation

/// The to-do list of attribution facts to fill in by hand: `docs/source-attribution-gaps.md`, made from the
/// catalog and the apps' source lists (`docs/source-usage/<app>.txt`). A source an app uses that is listed under
/// "Not in the catalog" or "Missing facts" fails that app's import.
public enum GapReport {
    /// The report, given each app's sources keyed by app name.
    public static func markdown(catalog: SourceCatalog, usage: [String: SourceTally]) -> String {
        let users = appsByTitle(usage, catalog: catalog)
        let unknown = users.keys.filter { catalog.entry(for: $0) == nil }.sorted(by: titleOrder)
        let incomplete = catalog.entries.filter { !$0.missingFacts.isEmpty }
        let unchecked = catalog.entries.filter { $0.missingFacts.isEmpty && !$0.verified }
        func used(_ title: String) -> String {
            let apps = users[title, default: []].sorted()
            return apps.isEmpty ? "not used by any app yet" : "used by \(apps.joined(separator: ", "))"
        }
        return header + [
            section("Not in the catalog", unknown.map { "\($0) — \(used($0))" }),
            section("Missing facts", incomplete.map {
                "\($0.title) (\($0.game)) — lacks \($0.missingFacts.joined(separator: ", ")) — \(used($0.title))"
            }),
            section("To check against the book's notice", unchecked.map {
                "\($0.title) (\($0.game)) — \($0.reference ?? "no reference") — \(used($0.title))"
            })
        ].joined(separator: "\n")
    }

    private static let header = """
        # Source attribution gaps

        Generated by `swift run SourceAttributionTool gaps docs/source-usage docs/source-attribution-gaps.md` \
        from `Sources/SourceAttribution/Resources/source-catalog.json` and the apps' source lists in \
        `docs/source-usage`. Don't edit this file: fill in the catalog, then generate it again.

        To fill a gap, take the title, copyright year, publisher and credits from the book's own copyright \
        notice, or its Paizo product page, and set `reference` to where you read them. Set `verified` to true \
        once the facts have been checked against the book's notice.


        """

    private static func section(_ title: String, _ lines: [String]) -> String {
        let items = lines.isEmpty ? "None.\n" : lines.map { "- [ ] \($0)\n" }.joined()
        return "## \(title) (\(lines.count))\n\n\(items)"
    }

    /// The apps that use each source, under its catalog title, or the app's own title when the catalog lacks it.
    private static func appsByTitle(_ usage: [String: SourceTally], catalog: SourceCatalog) -> [String: Set<String>] {
        var users: [String: Set<String>] = [:]
        for (app, tally) in usage {
            for source in tally.sources {
                users[catalog.entry(for: source.title)?.title ?? source.title, default: []].insert(app)
            }
        }
        return users
    }

    private static func titleOrder(_ first: String, _ second: String) -> Bool {
        first.localizedStandardCompare(second) == .orderedAscending
    }
}
